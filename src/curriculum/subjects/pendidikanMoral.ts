import type { Subject, Subtopic } from '@/types/curriculum';
import { buildAssessments, createSubtopic } from '../generators';

function createMoralValueSubtopic(params: {
  id: string;
  chapterId: string;
  code: string;
  num: number;
  valueName: string;
  emoji: string;
  summary: string;
  demoExample: string;
  items: Parameters<typeof buildAssessments>[1];
}): Subtopic {
  return createSubtopic({
    id: params.id,
    chapterId: params.chapterId,
    subjectId: 'pendidikan-moral',
    code: params.code,
    title: `Nilai ${params.num}: ${params.valueName}`,
    learningObjective: `Murid dapat memahami dan mengamalkan nilai ${params.valueName} dalam tema Diri Saya.`,
    engineId: 'moral-decision',
    engineConfig: { valueNumber: params.num, valueName: params.valueName },
    lessonSteps: [
      {
        id: `${params.id}-s1`,
        title: `Amalan Nilai ${params.valueName}`,
        body: params.summary,
        audioText: `Nilai ${params.valueName}: ${params.summary}`,
        exampleVisual: `${params.emoji} ${params.valueName}: ${params.demoExample}`,
      },
    ],
    interactiveDemo: {
      title: `Kad Nilai ${params.num}: ${params.valueName}`,
      prompt: 'Pilih kad untuk melihat contoh tingkah laku terpuji.',
      mode: 'posture',
      items: [
        { label: params.valueName, value: params.demoExample, emoji: params.emoji },
        { label: 'Manfaat Di Kampung', value: 'Semua penduduk berasa gembira, aman dan selamat.', emoji: '🏡' },
      ],
    },
    assessments: buildAssessments(params.id, params.items),
  });
}

function makeStandardMoralBank(
  valueName: string,
  goodAction: string,
  badAction: string,
  contextPlace: string,
  benefit: string,
): Parameters<typeof buildAssessments>[1] {
  return [
    {
      prompt: `Apakah maksud amalan nilai ${valueName} bagi murid Tahun 1?`,
      options: [goodAction, badAction, 'Mengabaikan rakan', 'Bersikap sombong'],
      correctAnswer: goodAction,
      hint: `Fikirkan tindakan positif berkaitan ${valueName}.`,
      explanation: `${valueName} diamalkan dengan ${goodAction.toLowerCase()}.`,
    },
    {
      prompt: `Di ${contextPlace}, bagaimanakah cara menunjukkan sikap ${valueName}?`,
      options: [goodAction, badAction, 'Menjerit kuat', 'Membuang sampah merata'],
      correctAnswer: goodAction,
      hint: 'Pilih teladan yang baik.',
      explanation: `${goodAction} ialah contoh amalan ${valueName} di ${contextPlace}.`,
    },
    {
      prompt: `Mengapakah kita perlu mengamalkan nilai ${valueName} setiap hari?`,
      options: [benefit, 'Supaya rakan takut kepada kita', 'Untuk memulakan pergaduhan', 'Kerana tiada kerja lain'],
      correctAnswer: benefit,
      hint: 'Nilai murni membawa kebaikan bersama.',
      explanation: `Amalan ${valueName} menghasilkan ${benefit.toLowerCase()}.`,
    },
    {
      prompt: `Jika melihat rakan melakukan sikap bertentangan dengan ${valueName} (${badAction.toLowerCase()}), kita patut...`,
      options: ['Menasihati dengan lembut dan menunjukkan contoh yang baik', 'Meniru perbuatan buruk itu', 'Mentertawakannya', 'Mendiamkan diri sambil mengejek'],
      correctAnswer: 'Menasihati dengan lembut dan menunjukkan contoh yang baik',
      hint: 'Jadilah teladan Wira Kampung.',
      explanation: 'Menasihati secara berhemah membantu rakan berubah.',
    },
    {
      prompt: `Apakah perasaan ibu bapa dan guru apabila kamu mengamalkan ${valueName}?`,
      options: ['Bangga dan gembira', 'Kecewa dan sedih', 'Marah', 'Bimbang'],
      correctAnswer: 'Bangga dan gembira',
      hint: 'Tingkah laku terpuji menggembirakan semua.',
      explanation: 'Ibu bapa dan guru gembira melihat akhlak mulia.',
    },
    {
      prompt: `Di Kampung Wira, siapakah yang patut mengamalkan nilai ${valueName}?`,
      options: ['Semua warga kampung termasuk kanak-kanak dan dewasa', 'Ketua kampung seorang', 'Haiwan sahaja', 'Pelancong sahaja'],
      correctAnswer: 'Semua warga kampung termasuk kanak-kanak dan dewasa',
      hint: 'Nilai murni tanggungjawab bersama.',
      explanation: 'Semua individu perlu mengamalkan nilai murni.',
    },
    {
      prompt: `Manakah tindakan yang TIDAK mencerminkan nilai ${valueName}?`,
      options: [badAction, goodAction, 'Bercakap sopan', 'Menolong kawan'],
      correctAnswer: badAction,
      hint: 'Cari perbuatan negatif.',
      explanation: `${badAction} bertentangan dengan nilai ${valueName}.`,
    },
    {
      prompt: `Bagaimanakah perasaan kamu sendiri selepas berjaya mengamalkan ${valueName}?`,
      options: ['Tenang, puas dan gembira', 'Gelisah', 'Takut', 'Rasa bersalah'],
      correctAnswer: 'Tenang, puas dan gembira',
      hint: 'Hati berasa damai apabila berbuat baik.',
      explanation: 'Berbuat baik memberi ketenangan jiwa.',
    },
    {
      prompt: `Apabila rakan baharu berpindah ke kelas, amalan ${valueName} membantu kita...`,
      options: ['Membina persahabatan yang harmoni', 'Mengasingkannya', 'Mencari gaduh', 'Menyorokkan bukunya'],
      correctAnswer: 'Membina persahabatan yang harmoni',
      hint: 'Kawan baharu perlukan sambutan mesra.',
      explanation: 'Nilai murni mengeratkan persahabatan.',
    },
    {
      prompt: `Pilih slogan terbaik untuk nilai ${valueName}:`,
      options: [`"${valueName} asas diri mulia"`, '"Pentingkan diri sendiri"', '"Biar orang lain buat"', '"Tidak perlu peduli"'],
      correctAnswer: `"${valueName} asas diri mulia"`,
      hint: 'Pilih slogan positif.',
      explanation: `${valueName} membentuk keperibadian mulia.`,
    },
  ];
}

